"""Embed trusted, bundled TrueType fonts for the standalone PDF writer.

Uses only the Python standard library. Font programs are compressed at build
time, ready for PDF's FlateDecode; no font files or Python are needed at runtime.
"""

import argparse
from pathlib import Path
import struct
import zlib


def font_data(path):
    data = path.read_bytes()
    u16 = lambda offset: struct.unpack_from(">H", data, offset)[0]
    i16 = lambda offset: struct.unpack_from(">h", data, offset)[0]
    u32 = lambda offset: struct.unpack_from(">I", data, offset)[0]
    assert data[:4] == b"\0\1\0\0", "Expected a static TrueType font"
    tables = {}
    for offset in range(12, 12 + 16 * u16(4), 16):
        tables[data[offset:offset + 4]] = u32(offset + 8)
    head, hhea, hmtx, cmap = (tables[tag] for tag in (b"head", b"hhea", b"hmtx", b"cmap"))
    scale = 1000 / u16(head + 18)
    metric_count = u16(hhea + 34)
    mappings = {}
    subtables = []
    for offset in range(cmap + 4, cmap + 4 + 8 * u16(cmap + 2), 8):
        platform, encoding = u16(offset), u16(offset + 2)
        if platform == 0 or (platform == 3 and encoding in (1, 10)):
            subtables.append(cmap + u32(offset + 4))
    for start in sorted(set(subtables), key=lambda at: u16(at)):
        if u16(start) == 12:
            for at in range(start + 16, start + 16 + 12 * u32(start + 12), 12):
                first, last, glyph = u32(at), u32(at + 4), u32(at + 8)
                for code in range(first, last + 1):
                    mappings[code] = glyph + code - first
        elif u16(start) == 4:
            count = u16(start + 6) // 2
            for index in range(count):
                end = u16(start + 14 + 2 * index)
                first = u16(start + 16 + 2 * count + 2 * index)
                delta = i16(start + 16 + 4 * count + 2 * index)
                at = start + 16 + 6 * count + 2 * index
                distance = u16(at)
                for code in range(first, min(end, 0xFFFE) + 1):
                    glyph = u16(at + distance + 2 * (code - first)) if distance else code
                    if glyph or not distance:
                        mappings[code] = (glyph + delta) & 0xFFFF
    glyphs = [(code, glyph, round(u16(hmtx + 4 * min(glyph, metric_count - 1)) * scale))
              for code, glyph in sorted(mappings.items()) if glyph and code <= 0x10FFFF]
    metrics = [round(i16(head + offset) * scale) for offset in (36, 38, 40, 42)]
    metrics += [round(i16(hhea + offset) * scale) for offset in (4, 6)]
    return data, glyphs, metrics


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("fonts", type=Path, nargs=3)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as output:
        output.write('// Generated by embed_pdf_fonts.py. Do not edit.\n#include "reports/pdf_document.hpp"\n'
                     'namespace crossvmaf::studio::pdf {\nnamespace {\n')
        records = []
        for index, path in enumerate(args.fonts):
            data, glyphs, metrics = font_data(path)
            compressed = zlib.compress(data, 9)
            output.write(f"const unsigned char program_{index}[] = {{\n")
            for start in range(0, len(compressed), 32):
                output.write(",".join(str(byte) for byte in compressed[start:start + 32]) + ",\n")
            output.write(f"}};\nconst Glyph glyphs_{index}[] = {{\n")
            for code, glyph, width in glyphs:
                output.write(f"{{{code},{glyph},{width}}},\n")
            output.write("};\n")
            records.append(f'{{"{path.stem}", program_{index}, sizeof(program_{index}), {len(data)}, '
                           f'glyphs_{index}, {len(glyphs)}, ' + '{' + ','.join(map(str, metrics)) + '}}')
        output.write("}\nconst FontAsset font_assets[3] = {\n" + ",\n".join(records) + "\n};\n}\n")


if __name__ == "__main__":
    main()
